import { useEffect, useRef, useState, type FormEvent, type KeyboardEvent } from 'react';
import { Link } from 'react-router';
import { Send, Trash2, User } from 'lucide-react';
import { Alert, Button, Modal, PageHeader, Skeleton } from '../../components/ui/primitives';
import { useToast } from '../../components/ui/Toaster';
import { Seo } from '../../lib/seo';
import { useI18n } from '../../lib/i18n';
import { useChat, useClearChat, useProfile, useSendChat } from '../../lib/queries';
import { ApiError } from '../../lib/api';
import { sourceLabel } from '../../lib/training';
import { getCoach } from '../../../shared/coaches';

export default function CoachPage() {
  const { t, lang, locale } = useI18n();
  const toast = useToast();
  const { data: profile } = useProfile();
  const { data, isLoading } = useChat();
  const send = useSendChat();
  const clear = useClearChat();
  const [text, setText] = useState('');
  const [confirmClear, setConfirmClear] = useState(false);
  const endRef = useRef<HTMLDivElement>(null);
  const coach = getCoach(profile?.coachId);
  const messages = data?.messages ?? [];

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' });
  }, [messages.length, send.isPending]);

  const submit = (value: string) => {
    const msg = value.trim();
    if (!msg || send.isPending) return;
    setText('');
    send.mutate(msg, {
      onError: (e) => {
        setText(msg);
        toast.error(e instanceof ApiError ? e.message : t("Message non envoyé.", 'Message not sent.'));
      },
    });
  };

  const onSubmit = (e: FormEvent) => {
    e.preventDefault();
    submit(text);
  };
  const onKeyDown = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      submit(text);
    }
  };

  const suggestions =
    lang === 'fr'
      ? ["J'ai une petite douleur au mollet, que faire ?", 'Comment mieux respirer en endurance ?', 'Que manger avant une sortie longue ?', "J'ai raté une séance, je la rattrape ?"]
      : ['I have a slight calf pain, what should I do?', 'How can I breathe better on easy runs?', 'What should I eat before a long run?', 'I missed a session, should I make it up?'];

  return (
    <div className="flex h-[calc(100dvh-11rem)] min-h-[28rem] flex-col lg:h-[calc(100dvh-8rem)]">
      <Seo title={t('Coach IA | ThusStride', 'AI coach | ThusStride')} noindex />
      <PageHeader
        title={coach.name}
        subtitle={coach.description[lang]}
        actions={
          messages.length > 0 && (
            <Button variant="ghost" size="sm" icon={<Trash2 className="h-4 w-4" />} onClick={() => setConfirmClear(true)}>
              {t('Effacer', 'Clear')}
            </Button>
          )
        }
      />

      {data && !data.aiAvailable && (
        <div className="mb-3">
          <Alert tone="warn">
            {t(
              "Aucun fournisseur d'IA n'est configuré sur ce serveur : le coach ne peut pas répondre pour le moment. Vos plans restent générés par le moteur de règles.",
              'No AI provider is configured on this server: the coach cannot answer right now. Your plans are still generated by the rules engine.',
            )}
          </Alert>
        </div>
      )}

      <div className="flex-1 overflow-y-auto rounded-2xl border border-white/10 bg-panel p-4 sm:p-6" aria-live="polite">
        {isLoading ? (
          <div className="space-y-3">
            <Skeleton className="h-16 w-2/3" />
            <Skeleton className="ml-auto h-12 w-1/2" />
          </div>
        ) : messages.length === 0 ? (
          <div className="flex h-full flex-col items-center justify-center text-center">
            <span className="flex h-14 w-14 items-center justify-center rounded-2xl bg-lime/15 font-display text-2xl font-bold text-lime">{coach.avatar}</span>
            <p className="mt-4 max-w-md text-sm text-white/60">
              {t(
                `Bonjour, je suis ${coach.name}. Posez-moi vos questions sur votre plan, vos allures, la récupération, la nutrition ou l'équipement.`,
                `Hi, I'm ${coach.name}. Ask me about your plan, paces, recovery, nutrition or gear.`,
              )}
            </p>
            <div className="mt-6 flex max-w-xl flex-wrap justify-center gap-2">
              {suggestions.map((s) => (
                <button
                  key={s}
                  onClick={() => submit(s)}
                  className="rounded-full border border-white/10 px-3 py-1.5 text-xs text-white/70 hover:border-lime/50 hover:text-white cursor-pointer"
                >
                  {s}
                </button>
              ))}
            </div>
            <p className="mt-6 text-xs text-white/30">
              {t('Le coach ne remplace pas un avis médical.', 'The coach is not a substitute for medical advice.')}{' '}
              <Link to="/app/profil" className="underline">
                {t('Changer de coach', 'Change coach')}
              </Link>
            </p>
          </div>
        ) : (
          <ol className="space-y-4">
            {messages.map((m) => {
              const mine = m.role === 'user';
              const c = getCoach(m.coachId);
              return (
                <li key={m.id} className={`flex gap-3 ${mine ? 'flex-row-reverse' : ''}`}>
                  <span
                    className={`flex h-8 w-8 shrink-0 items-center justify-center rounded-lg text-xs font-bold ${mine ? 'bg-white/10 text-white' : 'bg-lime/15 text-lime'}`}
                    aria-hidden="true"
                  >
                    {mine ? <User className="h-4 w-4" /> : c.avatar}
                  </span>
                  <div className={`max-w-[85%] rounded-2xl px-4 py-3 text-sm leading-relaxed ${mine ? 'bg-lime text-black' : 'border border-white/10 bg-white/[0.03] text-white/90'}`}>
                    <span className="sr-only">{mine ? t('Vous :', 'You:') : `${c.name} :`}</span>
                    <p className="whitespace-pre-line">{m.content}</p>
                    <p className={`mt-1.5 text-[11px] ${mine ? 'text-black/50' : 'text-white/30'}`}>
                      {new Date(m.createdAt).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' })}
                      {!mine && m.source && ` · ${sourceLabel(m.source, lang)}`}
                    </p>
                  </div>
                </li>
              );
            })}
            {send.isPending && (
              <li className="flex gap-3">
                <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-lime/15 text-xs font-bold text-lime">{coach.avatar}</span>
                <div className="flex items-center gap-1.5 rounded-2xl border border-white/10 bg-white/[0.03] px-4 py-3" role="status">
                  <span className="sr-only">{t('Le coach écrit…', 'Coach is typing…')}</span>
                  {[0, 150, 300].map((d) => (
                    <span key={d} className="h-2 w-2 animate-bounce rounded-full bg-lime" style={{ animationDelay: `${d}ms` }} />
                  ))}
                </div>
              </li>
            )}
          </ol>
        )}
        <div ref={endRef} />
      </div>

      <form onSubmit={onSubmit} className="mt-3 flex items-end gap-2">
        <label htmlFor="chat-input" className="sr-only">
          {t('Votre message', 'Your message')}
        </label>
        <textarea
          id="chat-input"
          rows={1}
          value={text}
          maxLength={2000}
          onChange={(e) => setText(e.target.value)}
          onKeyDown={onKeyDown}
          placeholder={t('Écrivez à votre coach…', 'Message your coach…')}
          className="max-h-40 min-h-12 flex-1 resize-none rounded-xl border border-white/10 bg-white/[0.04] px-4 py-3 text-sm text-white placeholder-white/30 focus:outline-none focus:ring-2 focus:ring-lime/60"
        />
        <Button type="submit" size="lg" className="!h-12 !px-4" disabled={!text.trim()} loading={send.isPending} aria-label={t('Envoyer', 'Send')}>
          {!send.isPending && <Send className="h-4 w-4" />}
        </Button>
      </form>

      <Modal
        open={confirmClear}
        onClose={() => setConfirmClear(false)}
        title={t('Effacer la conversation ?', 'Clear the conversation?')}
        footer={
          <>
            <Button variant="ghost" onClick={() => setConfirmClear(false)}>
              {t('Annuler', 'Cancel')}
            </Button>
            <Button variant="danger" loading={clear.isPending} onClick={() => clear.mutate(undefined, { onSuccess: () => setConfirmClear(false) })}>
              {t('Effacer', 'Clear')}
            </Button>
          </>
        }
      >
        <p className="text-sm text-white/70">{t('Tous les messages seront définitivement supprimés.', 'All messages will be permanently deleted.')}</p>
      </Modal>
    </div>
  );
}
